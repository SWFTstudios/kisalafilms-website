INHERITED = [
    r'[ \t]*<!-- JSON-LD: generated by scripts/build-jsonld\.mjs -->\s*<script type="application/ld\+json">[\s\S]*?</script>\n',
    r'[ \t]*<script type="application/ld\+json">[\s\S]*?</script>\n',
    r'[ \t]*<!-- SEO: generated by scripts/build-seo\.py -->\n',
    r'[ \t]*<link rel="canonical"[^>]*>\n',
    r'[ \t]*<meta property="og:[^"]+"[^>]*>\n',
    r'[ \t]*<meta name="twitter:[^"]+"[^>]*>\n',
    r'[ \t]*<meta name="robots"[^>]*>\n',
]


def esc(text: str) -> str:
    return html.escape(text, quote=True)


def chrome() -> tuple[str, str, str]:
    raw = SOURCE.read_text(encoding="utf-8")
    head = re.search(r"<!DOCTYPE html>.*?<head>\n(.*?)</head>", raw, re.S)
    header = re.search(r"(<header class=\"site-header\">.*?</aside>\s*)", raw, re.S)
    footer = re.search(r"(<footer class=\"site-footer\">.*?</html>\s*)", raw, re.S)
    if not (head and header and footer):
        raise SystemExit("Could not read the chrome out of shop.html")
    return head.group(1), header.group(1), footer.group(1)


def head_for(title: str, description: str, head_template: str) -> str:
    head = head_template
    for pattern in INHERITED:
        head = re.sub(pattern, "", head)
    # Scripts are re-inserted by page_shell so they cannot stack across rebuilds.
    head = re.sub(r'[ \t]*<script src="/js/kisala-config\.js"></script>\n', "", head)
    head = re.sub(r'[ \t]*<script src="/js/analytics\.js"></script>\n', "", head)
    head = re.sub(r"<title>.*?</title>", f"<title>{esc(title)}</title>", head, flags=re.S)
    return re.sub(
        r'<meta name="description" content=".*?">',
        f'<meta name="description" content="{esc(description)}">',
        head,
        flags=re.S,
    )


def breadcrumbs(*crumbs: tuple[str, str]) -> str:
    items = []
    for i, (name, path) in enumerate(crumbs, start=1):
        url = SITE + path if path != "/" else SITE + "/"
        items.append(
            f"""          {{
            "@type": "ListItem",
            "position": {i},
            "name": {json.dumps(name)},
            "item": {json.dumps(url)}
          }}"""
        )
    return f"""  <script type="application/ld+json">
  {{
    "@context": "https://schema.org",
    "@graph": [
      {{
        "@type": "BreadcrumbList",
        "itemListElement": [
{',\n'.join(items)}
        ]
      }}
    ]
  }}
  </script>
"""


def page_shell(
    *,
    title: str,
    description: str,
    head_template: str,
    header: str,
    body: str,
    footer: str,
    crumbs: list[tuple[str, str]],
    extra_scripts: str = "",
) -> str:
    # Footer block from chrome() includes scripts through </html>. Strip the
    # trailing scripts so we can re-add a consistent set, then append extras.
    footer_only = re.sub(
        r"\n  <script src=.*?</html>\s*\Z",
        "\n",
        footer,
        flags=re.S,
    )
    scripts = (
        '  <script src="/js/config-apply.js"></script>\n'
        '  <script src="/js/nav.js"></script>\n'
        '  <script src="/js/site.js"></script>\n'
        f"{extra_scripts}"
        "</body>\n</html>\n"
    )
    return (
        "<!DOCTYPE html>\n"
        '<html lang="en">\n'
        "<head>\n"
        f"{head_for(title, description, head_template)}"
        f"{breadcrumbs(*crumbs)}"
        '  <script src="/js/kisala-config.js"></script>\n'
        '  <script src="/js/analytics.js"></script>\n'
        "</head>\n"
        '<body class="carsy">\n\n'
        f"{header.rstrip()}\n\n"
        f"{body.lstrip()}\n"
        f"{footer_only.rstrip()}\n"
        f"{scripts}"
    )


