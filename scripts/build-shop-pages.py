"""Generate the shop hub, collection pages, and product pages.

Chrome is duplicated per page across this site rather than templated, so these
are composed from shop.html's header/footer/<head> and written out as static
files — the same approach build-local-pages.py uses for city landings.

Data:
  public/data/shop-catalog.json  — collections, wrap finishes, photoshoot pkgs
  public/data/products.json      — merch drop

Outputs:
  public/shop.html
  public/shop/{photoshoot,wrap,merch}.html
  public/shop/photoshoot/*.html
  public/shop/wrap/*.html
  public/shop/merch/*.html

Usage:
  python3 scripts/build-shop-pages.py
"""

