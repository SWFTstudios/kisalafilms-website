/* ---- Write ------------------------------------------------------------- */
function block(graph) {
  const payload = JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 2)
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
  // No trailing newline: the anchor line's own newline terminates it, which is
  // what keeps a re-run from gaining a blank line each time.
  return `${MARK_OPEN}\n  <script type="application/ld+json">\n${payload}\n  </script>`;
}

/**
 * Strip a previous run's block so re-running cannot stack them up.
 *
 * Takes the block's own trailing newline with it and leaves the anchor line's
 * newline alone, so strip and insert are exact inverses. Getting that wrong is
 * silent: the page still renders, it just grows a blank line per build.
 */
function stripExisting(html) {
  return html.replace(
    /[ \t]*<!-- JSON-LD: generated by scripts\/build-jsonld\.mjs -->\s*<script type="application\/ld\+json">[\s\S]*?<\/script>\n/g,
    ""
  );
}

let count = 0;
for (const [rel, build] of Object.entries(PAGES)) {
  const path = join(PUBLIC, rel);
  let html = stripExisting(readFileSync(path, "utf8"));

  const graph = build(html);
  // Anchored to the stylesheet link. A page registered above that has no link to
  // anchor to is a mistake worth shouting about rather than skipping quietly —
  // silently skipping is how the home page's structured data once froze at what
  // it said before the redesign.
  const anchor = [
    '  <link rel="stylesheet" href="/css/kfilms.css">',
    '  <link rel="stylesheet" href="/css/kf.css">',
  ].find((a) => html.includes(a));
  if (!anchor) {
    console.error(`${rel}: no stylesheet anchor, skipped`);
    continue;
  }

  html = html.replace(anchor, `${anchor}\n${block(graph)}`, 1);
  writeFileSync(path, html, "utf8");

  const types = graph.map((n) => n["@type"]);
  console.log(`${rel.padEnd(36)} ${types.join(", ")}`);
  count += 1;
}

console.log(`\n${count} pages carry JSON-LD (pricing mode: ${RESOLVER.mode})`);
