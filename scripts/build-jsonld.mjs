/**
 * Cloudflare Static Assets serves these extensionless and 307-redirects the
 * .html form, so structured data has to name the URL that actually resolves.
 * Kept in step with canonical_path() in scripts/build-seo.py.
 */
const url = (path) => SITE + (path === "/" ? "/" : path.replace(/\.html$/, ""));

const breadcrumbs = (trail) => ({
  "@type": "BreadcrumbList",
  itemListElement: trail.map(([name, path], i) => ({
    "@type": "ListItem",
    position: i + 1,
    name,
    item: url(path),
  })),
});

/* ---- FAQ, read off the page so the two cannot disagree ------------------ */
function readFaq(html) {
  const items = [...html.matchAll(
    /<button class="faq-q"[^>]*>(.*?)<span class="mark">.*?<\/button>\s*<p class="faq-a">(.*?)<\/p>/gs
  )];
  return items.map(([, q, a]) => [plain(q), plain(a)]);
}

/** Markup and entities out: JSON-LD has to be plain text. */
function plain(text) {
  return text
    .replace(/<[^>]+>/g, "")
    .replace(/&mdash;/g, "—")
    .replace(/&ndash;/g, "–")
    .replace(/&rsquo;/g, "\u2019")
    .replace(/&lsquo;/g, "\u2018")
    .replace(/&amp;/g, "&")
    .replace(/&nbsp;/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const faqPage = (pairs) => ({
  "@type": "FAQPage",
  mainEntity: pairs.map(([name, answer]) => ({
    "@type": "Question",
    name,
    acceptedAnswer: { "@type": "Answer", text: answer },
  })),
});

/* ---- Offers, priced from the live config ------------------------------- */
function offer(key, name, description) {
  const price = RESOLVER.servicePrice(key);
  return {
    "@type": "Service",
    name,
    description,
    serviceType: name,
    provider: { "@id": GARAGE_ID },
    areaServed: CONFIG.zones.filter((z) => z.available && z.page).map((z) => ({
      "@type": "City",
      name: z.id === "nyc" ? "New York" : z.short,
    })),
    offers: {
      "@type": "Offer",
      priceCurrency: "USD",
      // A range, because the real number depends on the bike. lowPrice is what
      // the page quotes as "from".
      priceSpecification: {
        "@type": "PriceSpecification",
        priceCurrency: "USD",
        minPrice: price.low,
        maxPrice: price.high,
      },
      availability: "https://schema.org/LimitedAvailability",
    },
  };
}

